//! A build as a popmenu (`.mnu`) — the test-server file that grants every slotted enhancement.
//!
//! The file goes in the game's `data/texts/English/Menus/` folder and opens with
//! `/popmenu <name>`. Each option runs a `$$`-joined chain of `boost <record> <record> <level>`
//! commands, so the whole job of this module is naming each slotted piece the way the game's own
//! record namespace does. The port of the beta's `utils/export-popmenu.ts`.
//!
//! **Every name is a reverse read of the boost index, never assembled from our ids.** The beta
//! assembled at first — a planner-stat table and a prefix/PascalCase composition for set
//! pieces — and the table spelled Fly `Crafted_Flight` and Slow `Crafted_Slow` where the game
//! has `Crafted_Fly` and `Crafted_Snare`. `boost` answers an unknown record with a console line
//! nobody reads and grants nothing, so it shipped that way for eleven months (POPMENU-1).
//!
//! **A piece that cannot be named is reported, not dropped.** In game an unnameable piece is
//! indistinguishable from one this file never wrote, which is exactly how POPMENU-1 hid. So
//! [`Popmenu::warnings`] says which power and slot, and why.
//!
//! **Boosters are not carried.** The game's `boost` command takes no combine count, so no
//! popmenu can state one; a boosted piece arrives at its base level. Origin pieces are left out
//! too — see [`record_for`].

use crate::boost_index::{BoostEntry, BoostIndex};
use crate::character::{CharacterState, Enhancement, EnhancementKind, SelectedPower};
use crate::database::PowerDatabase;

/// Boost commands per `Option` line. The game caps a command's length, and the beta's limit has
/// held in use, so it is kept rather than re-derived.
const MAX_BOOSTS_PER_OPTION: usize = 70;

/// The level the command states for a piece with none of its own: an attuned piece, a special,
/// and a crafted piece that defers to the build. 50 is what the beta wrote and what the auction
/// identifier reads the deferral as.
const DEFAULT_LEVEL: u8 = 50;

/// Why a slotted piece is not in the file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WarningKind {
    /// This dataset's boost index names no record for it.
    Unnameable,
    /// A record exists but the planner does not hold enough to pick it (origin pieces).
    NotGrantable,
}

/// One slotted piece the menu will not grant.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PopmenuWarning {
    pub kind: WarningKind,
    /// The power the slot belongs to, as the user sees it named.
    pub power: String,
    /// 1-based slot within that power.
    pub slot: usize,
    pub detail: String,
}

/// The file, and what it could not grant.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Popmenu {
    pub content: String,
    pub warnings: Vec<PopmenuWarning>,
}

/// The menu name to offer for a build: its name with everything but ASCII letters and digits
/// turned to `_`, or `MyBuild`. The name is typed after `/popmenu` and is the file's stem, so it
/// has to survive both.
pub fn default_menu_name(build: &CharacterState) -> String {
    let name: String = build
        .name
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    if name.is_empty() {
        "MyBuild".to_string()
    } else {
        name
    }
}

/// Generate the popmenu for `build`.
///
/// `stamp` is the generation time as the header should print it — the caller's, because this
/// crate reads no clock.
pub fn generate(
    build: &CharacterState,
    database: &PowerDatabase,
    index: &BoostIndex,
    menu_name: &str,
    stamp: &str,
) -> Popmenu {
    let mut warnings = Vec::new();
    let mut commands = Vec::new();

    for (power, slot, enhancement) in slotted(build) {
        match record_for(enhancement, index) {
            Ok((record, level)) => commands.push(format!("boost {record} {record} {level}")),
            Err((kind, detail)) => warnings.push(PopmenuWarning {
                kind,
                power: power_name(power, database),
                slot,
                detail,
            }),
        }
    }

    if commands.is_empty() {
        return Popmenu {
            content: "// No exportable enhancements found in build\n".to_string(),
            warnings,
        };
    }

    let chunks: Vec<&[String]> = commands.chunks(MAX_BOOSTS_PER_OPTION).collect();
    let mut lines = vec![
        format!("// Generated by Sidekick - {stamp}"),
        format!("// Open the menu in game: /popmenu {menu_name}"),
        String::new(),
        format!("Menu \"{menu_name}\""),
        "{".to_string(),
        "\tTitle \"Test build\"".to_string(),
        "\tDIVIDER".to_string(),
    ];
    for (i, chunk) in chunks.iter().enumerate() {
        let label = if chunks.len() == 1 {
            "Give enhancements".to_string()
        } else {
            format!("Give enhancements (part {})", i + 1)
        };
        lines.push(format!("\tOption \"{label}\" \"{}\"", chunk.join("$$")));
    }
    for line in [
        "\tDIVIDER",
        "\tLockedOption",
        "\t{",
        "\t\tDisplayName \"Sidekick\"",
        "\t\tBadge \"X\"",
        "\t}",
        "\tLockedOption",
        "\t{",
    ] {
        lines.push(line.to_string());
    }
    lines.push(format!("\t\tDisplayName \"Generated: {stamp}\""));
    for line in ["\t\tBadge \"X\"", "\t}", "}", ""] {
        lines.push(line.to_string());
    }

    Popmenu {
        content: lines.join("\n"),
        warnings,
    }
}

/// Every filled slot, in the order the menu grants them: primary, secondary, pools, epic,
/// inherents. The slot number is 1-based, as a warning names it.
fn slotted(build: &CharacterState) -> impl Iterator<Item = (&SelectedPower, usize, &Enhancement)> {
    build
        .primary
        .powers
        .iter()
        .chain(&build.secondary.powers)
        .chain(build.pools.iter().flat_map(|pool| &pool.powers))
        .chain(build.epic_pool.iter().flat_map(|pool| &pool.powers))
        .chain(&build.inherents)
        .flat_map(|power| {
            power
                .slots
                .iter()
                .enumerate()
                .filter_map(move |(i, slot)| slot.as_ref().map(|enh| (power, i + 1, enh)))
        })
}

fn power_name(power: &SelectedPower, database: &PowerDatabase) -> String {
    database
        .resolve_power(&power.powerset, &power.internal_name)
        .map_or_else(|| power.internal_name.clone(), |def| def.name.clone())
}

/// The record the game knows this piece by and the level to grant it at, or why it has none.
fn record_for(
    enhancement: &Enhancement,
    index: &BoostIndex,
) -> Result<(String, u8), (WarningKind, String)> {
    let unnameable = |detail: String| (WarningKind::Unnameable, detail);
    match &enhancement.kind {
        EnhancementKind::IoSet {
            set_id,
            set_name,
            piece_num,
            ..
        } => {
            let attuned = enhancement.attuned;
            let record = index
                .io_set_records(set_id, *piece_num)
                .iter()
                .find(|name| {
                    matches!(index.get(name), Some(BoostEntry::IoSet { attuned: a, .. }) if *a == attuned)
                })
                .ok_or_else(|| {
                    let form = if attuned { "attuned " } else { "" };
                    unnameable(format!(
                        "this server's export names no {form}{set_name} piece {piece_num}"
                    ))
                })?;
            // An attuned piece states no craft level; the game holds it at the character's,
            // and 50 is what the command has to say to mean that.
            let level = if attuned {
                DEFAULT_LEVEL
            } else {
                enhancement.level.map_or(DEFAULT_LEVEL, |level| level.get())
            };
            Ok((record.clone(), level))
        }

        EnhancementKind::GenericIo { stat, .. } => match index.common_io_template(stat) {
            Ok(record) => Ok((
                record.to_string(),
                enhancement.level.map_or(DEFAULT_LEVEL, |level| level.get()),
            )),
            Err(candidates) if candidates.is_empty() => Err(unnameable(format!(
                "this server's export names no {stat} generic IO"
            ))),
            // Picking one of several would be a coin toss written into a file the game executes.
            Err(candidates) => Err(unnameable(format!(
                "this server's export has no single {stat} generic IO among {}",
                candidates.join(", ")
            ))),
        },

        EnhancementKind::Special { category, .. } => {
            // The model's id is `<category>-<registry id>`; the seam is the category, not the
            // first dash (`d-sync-optimization` has three).
            let id = enhancement
                .id
                .strip_prefix(category.as_str())
                .and_then(|rest| rest.strip_prefix('-'));
            let record = id.and_then(|id| {
                index.entries.iter().find_map(|(name, entry)| match entry {
                    BoostEntry::Special {
                        family,
                        id: entry_id,
                    } if family == category && entry_id == id => Some(name),
                    _ => None,
                })
            });
            match record {
                // Specials pin no craft level; the game holds them at 50.
                Some(record) => Ok((record.clone(), DEFAULT_LEVEL)),
                None => Err(unnameable(format!(
                    "this server's export names no {} record",
                    enhancement.name
                ))),
            }
        }

        // TO/DO/SO records exist and `boost` would grant them, but WHICH one is a question the
        // slot does not answer: the game names a DO for each PAIR of origins, so a Magic
        // character has two spellings and the planner stores neither. Left out rather than
        // guessed at — they cost a few thousand influence in game.
        EnhancementKind::Origin { .. } => Err((
            WarningKind::NotGrantable,
            "origin enhancements are bought in game, not granted by popmenu".to_string(),
        )),
    }
}
